const DAY_NAMES = {
    pl: ["niedz.", "pon.", "wt.", "śr.", "czw.", "pt.", "sob."],
    en: ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
};

let currentLang = (function () {
    try {
        const saved = localStorage.getItem(LANG_KEY);
        if (LANGS.indexOf(saved) >= 0) return saved;
    } catch (e) {
        /* storage unavailable */
    }
    return "pl"; // Polish is the default for the target users
})();

function lang() {
    return currentLang;
}

function setLang(code) {
    if (LANGS.indexOf(code) < 0) return;
    currentLang = code;
    try {
        localStorage.setItem(LANG_KEY, code);
    } catch (e) {
        /* storage unavailable */
    }
}

/** Text for a key in the current language, with {placeholders} filled in. Falls back to Polish. */
function t(key, params) {
    let text = TEXTS[currentLang][key];
    if (text === undefined) text = TEXTS.pl[key];
    if (text === undefined) return key;
    if (params) {
        Object.keys(params).forEach(function (name) {
            text = text.split("{" + name + "}").join(String(params[name]));
        });
    }
    return text;
}

/** Polish plural forms: 1 → one, 2–4 (not 12–14) → few, otherwise → many. English uses one / many. */
function tPlural(base, n) {
    let form;
    if (currentLang === "pl") {
        if (n === 1) form = "one";
        else if (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14)) form = "few";
        else form = "many";
    } else {
        form = n === 1 ? "one" : "many";
    }
    return t(base + "_" + form, { n: n });
}
